def generate_dataset(
    n_safe: int = 1500,
    n_suspicious: int = 750,
    n_malicious: int = 750,
    seed: int = 42,
) -> pd.DataFrame:
    """
    Generate a labelled synthetic dataset.

    Returns a DataFrame with columns = FEATURE_NAMES + ["label"].
    """
    rng = np.random.default_rng(seed)
    rows: List[np.ndarray] = []
    labels: List[str] = []

    class_counts = {
        "safe":       n_safe,
        "suspicious": n_suspicious,
        "malicious":  n_malicious,
    }

    for cls, count in class_counts.items():
        dist = _DIST[cls]
        for _ in range(count):
            features = np.array([
                float(np.clip(rng.normal(mean, std), lo, hi))
                for mean, std, lo, hi in dist
            ], dtype=np.float32)

            # Binary features: round to 0/1
            binary_indices = [
                0, 1, 3, 13, 14, 15, 16, 17, 19, 20, 22, 23
            ]
            for idx in binary_indices:
                features[idx] = float(round(min(max(features[idx], 0.0), 1.0)))

            rows.append(features)
            labels.append(cls)

    X = np.stack(rows)
    df = pd.DataFrame(X, columns=FEATURE_NAMES)
    df["label"] = labels

    # Shuffle
    df = df.sample(frac=1, random_state=seed).reset_index(drop=True)

    logger.info(
        "Generated dataset: %d safe, %d suspicious, %d malicious  (%d total)",
        n_safe, n_suspicious, n_malicious, len(df),
    )
    return df


