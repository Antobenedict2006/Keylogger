"""
train_model.py
==============
Synthetic training-data generator + model trainer for the Keylogger
Detection System.

What it does
------------
1. Generates a labelled CSV dataset of realistic feature vectors for three
   classes: safe, suspicious, malicious.
2. Trains a scikit-learn Pipeline (StandardScaler + Gradient Boosting or
   Random Forest — configurable via --model-type).
3. Evaluates the model with stratified k-fold cross-validation and prints a
   classification report on a held-out test set.
4. Serialises the trained pipeline + metadata to models/keylogger_detector.joblib.
   The running detector hot-reloads this file automatically.

Synthetic data design
---------------------
Each class is generated by sampling from per-class distributions that encode
real-world knowledge about how keyloggers differ from benign processes:

  safe      : No hook APIs, visible window, low I/O, signed, system/standard apps.
  suspicious: Hook APIs present but ambiguous (accessibility tools, macro apps).
              Sometimes no window, some file writes, maybe one startup entry.
  malicious : Strong hook signals, hidden, high network send after keystrokes,
              running from temp dirs, startup persistence, unsigned.

Usage
-----
  python tools/train_model.py                      # train with defaults
  python tools/train_model.py --samples 5000       # larger dataset
  python tools/train_model.py --model-type rf      # Random Forest
  python tools/train_model.py --output models/my_model.joblib
  python tools/train_model.py --csv data/training_data.csv  # save dataset
  python tools/train_model.py --load-csv data/real_data.csv # train on real data

Real data
---------
  If you have collected labelled real process snapshots (e.g. from sandbox
  runs), export them as a CSV with columns matching FEATURE_NAMES plus a
  "label" column ("safe"/"suspicious"/"malicious"), then pass --load-csv.
  The script will train on that data instead of the synthetic set.
"""

