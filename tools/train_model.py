# Model training
# ---------------------------------------------------------------------------

def train(
    df: pd.DataFrame,
    model_type: str = "gb",
    n_estimators: int = 300,
    test_size: float = 0.20,
    cv_folds: int = 5,
    seed: int = 42,
) -> Tuple:
    """
    Train and evaluate a scikit-learn Pipeline on *df*.

    Parameters
    ----------
    df          : DataFrame with FEATURE_NAMES columns + "label" column.
    model_type  : "gb" = GradientBoostingClassifier, "rf" = RandomForestClassifier
    n_estimators: tree count for the ensemble
    test_size   : fraction of data held out for final evaluation
    cv_folds    : number of stratified cross-validation folds
    seed        : random seed

    Returns
    -------
    pipeline  : fitted sklearn Pipeline
    report    : classification report string
    cv_scores : array of CV accuracy scores
    """
    from sklearn.ensemble import (
        GradientBoostingClassifier,
        RandomForestClassifier,
    )
    from sklearn.metrics import classification_report
    from sklearn.model_selection import StratifiedKFold, cross_val_score, train_test_split
    from sklearn.pipeline import Pipeline
    from sklearn.preprocessing import StandardScaler

    X = df[FEATURE_NAMES].values.astype(np.float32)
    y = df["label"].values

    # Encode labels to integers for cross_val_score, then decode back
    y_int = np.array([LABEL_INT[l] for l in y])

    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=test_size, stratify=y, random_state=seed
    )

    if model_type == "rf":
        estimator = RandomForestClassifier(
            n_estimators=n_estimators,
            max_depth=None,
            min_samples_leaf=2,
            n_jobs=-1,
            random_state=seed,
            class_weight="balanced",
        )
        model_name = "RandomForest"
    else:
        estimator = GradientBoostingClassifier(
            n_estimators=n_estimators,
            learning_rate=0.08,
            max_depth=5,
            subsample=0.8,
            random_state=seed,
        )
        model_name = "GradientBoosting"

    pipeline = Pipeline([
        ("scaler",     StandardScaler()),
        ("classifier", estimator),
    ])

    # Cross-validation
    logger.info("Running %d-fold cross-validation with %s…", cv_folds, model_name)
    cv_start = time.time()
    skf = StratifiedKFold(n_splits=cv_folds, shuffle=True, random_state=seed)
    cv_scores = cross_val_score(
        pipeline, X_train, y_train,
        cv=skf, scoring="f1_macro", n_jobs=-1,
    )
    logger.info(
        "CV F1-macro: %.3f ± %.3f  (%.1fs)",
        cv_scores.mean(), cv_scores.std(),
        time.time() - cv_start,
    )

    # Final fit on full training set
    logger.info("Fitting final model on %d training samples…", len(X_train))
    fit_start = time.time()
    pipeline.fit(X_train, y_train)
    logger.info("Training complete in %.1fs.", time.time() - fit_start)

    # Evaluate on held-out test set
    y_pred = pipeline.predict(X_test)
    report = classification_report(
        y_test, y_pred,
        target_names=LABELS,
        digits=3,
    )

    return pipeline, report, cv_scores


